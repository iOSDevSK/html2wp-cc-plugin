#!/usr/bin/env python3
"""Live fix: repair a theme that already passed its gate, without converting
again (SKILL.md "Live fix").

  live-fix.py start   --workspace WS [--mode flash|full] [--report PATH] [--input DIR]
  live-fix.py log     --workspace WS --note TEXT [--script-review PATH=REASON ...]
  live-fix.py revert  --workspace WS --to N          (N fixes kept; 0 = the base)
  live-fix.py status  --workspace WS
  live-fix.py check   --workspace WS [--wp-cli PREFIX | --env .test-env-<slug>.json]
  live-fix.py certify --workspace WS  --wp-cli PREFIX | --env .test-env-<slug>.json [--state PATH]
  live-fix.py check-path --workspace WS --path P [--path P ...] [--content-file F (one --path)]
  live-fix.py verify-package --workspace WS [--report PATH] [--quick PATH] [--state PATH]
  live-fix.py deliver --workspace WS --zip PATH [--report PATH] [--quick PATH] [--state PATH]
  live-fix.py guard   --workspace WS
  live-fix.py discard --workspace WS
  live-fix.py levers

The workspace theme ({workspace}/theme/<slug>) stays the only truth: the fix
is an edit of its files (content in content/*.json, in the bundle's own
tokenized form), the preview receives it through `install` (upload plus the
guarded re-import), and the ZIP is packed from it. What a live fix may never
touch is enforced here, not by convention:
  - the files the converter owns (functions.php, inc/, the runtime assets):
    a bug there is a converter gap, reported and fixed in the converter;
  - the inputs of the conversion (source, dist, manifest, block plan): a
    change there is a re-conversion, which discards the live fixes;
  - a changed script needs Flash's script scan (Flash) or a recorded review
    (full), as when the conversion listed it;
  - changed block markup must keep the block grammar (delimiters that parse,
    open and close in order, attributes one JSON object).

{workspace}/live-fix.json is the mark: the base the fixes start from, and the
log of every fix; .live-fix/objects/ keeps every version it names, so any fix
can be reverted. `check` measures a preview (live-fix-check.json); `certify`
measures the fresh install the delivery is certified on (live-fix-state.json),
bound by the liveDigest that packaging recomputes. Every refusal carries its
code and the lever that clears it (`levers` lists them all). Output is JSON on
stdout; exit 1 on a refusal.
"""
